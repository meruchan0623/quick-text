# Source allowlist for the corresponding-source ZIP / folder (GPL-3.0-or-later, S-28; B-51).
#
# Dot-sourced by scripts/package-artifacts.ps1 (Source.zip), scripts/package-portable.ps1
# (source/ folder) and scripts/check-source-allowlist.ps1 (coverage check in CI and in the
# release workflow). It is the only place that decides which files are shipped as source.
#
# Why an explicit allowlist: the working tree also holds runtime configuration, imports,
# logs, build products and private data (see .gitignore). They must never be swept into a
# public archive by a recursive copy.
#
# WHEN TO UPDATE (B-51 "after adding a crate, update the source allowlist"):
#   * new workspace crate (crates/<name>, e.g. crates/engine in 0.5): add its Cargo.toml,
#     README.md and build.rs (if any) to $SourceFiles and its src/tests/examples/benches
#     directories to $SourceDirectories;
#   * new root-level build or config file (eslint.config.js, vitest.config.ts, tsconfig.*.json,
#     rustfmt.toml, ...): add it to $SourceFiles;
#   * a tracked file that must not ship: add it to $SourceExcluded with the reason.
# scripts/check-source-allowlist.ps1 fails when a workspace crate has a tracked file that is
# neither listed nor excluded, and the release workflow runs it with -Strict (every tracked
# file must be classified).
#
# crates.io and npm dependencies are NOT listed here: they are not part of this repository.
# Their source ships in the separate Quicker-Text-<version>-Source-deps.zip
# (scripts/package-dependency-sources.ps1), and Source.zip plus Source-deps.zip together are the
# complete corresponding source. Cargo.lock and package-lock.json (both listed) pin the exact
# versions and checksums that archive was made from. See docs/release-checklist.md.
#
# Paths use '/' (valid on Windows and elsewhere) and are relative to the repository root.

$SourceFiles = @(
    '.gitattributes',
    '.gitignore',
    '.prettierignore',
    '.prettierrc',
    'Cargo.lock',
    'Cargo.toml',
    'LICENSE',
    'README.md',
    'THIRD_PARTY_NOTICES.md',
    'deny.toml',
    'eslint.config.js',
    'index.html',
    'package-lock.json',
    'package.json',
    'tsconfig.json',
    'vite.config.ts',
    'vitest.config.ts',
    'vendor/espanso-win32/LICENSE',
    'crates/domain/Cargo.toml',
    'crates/domain/README.md',
    'crates/platform/Cargo.toml',
    'crates/platform/build.rs',
    'src-tauri/Cargo.toml',
    'src-tauri/build.rs',
    'src-tauri/tauri.conf.json'
)

# Directories are traversed recursively; only files with an extension in $SourceExtensions
# are taken. Missing directories are skipped (benches/ and tests/ exist only in some crates).
$SourceDirectories = @(
    '.github',
    'crates/domain/benches',
    'crates/domain/examples',
    'crates/domain/src',
    'crates/domain/tests',
    'crates/platform/benches',
    'crates/platform/examples',
    'crates/platform/src',
    'crates/platform/tests',
    'docs',
    'scripts',
    'src',
    'src-tauri/capabilities',
    'src-tauri/icons',
    'src-tauri/resources',
    'src-tauri/src',
    'vendor'
)

$SourceExtensions = @(
    '.cpp', '.css', '.h', '.html', '.ico', '.json', '.md', '.mjs', '.png', '.ps1', '.rs',
    '.sh', '.ts', '.tsx', '.txt', '.yml'
)

# Tracked files that are deliberately not shipped (path prefix or exact path, with reason).
# check-source-allowlist.ps1 -Strict needs every tracked file to be shipped or listed here.
$SourceExcluded = @(
    [pscustomobject]@{ Path = '.claude/';          Reason = 'local assistant/editor tooling configuration, not part of the program' }
    [pscustomobject]@{ Path = '.git-blame-ignore-revs'; Reason = 'git history helper; the archive has no git history' }
    [pscustomobject]@{ Path = 'src-tauri/gen/';    Reason = 'generated by tauri-build on every build' }
)

function Get-SourceAllowlist {
    <#
    .SYNOPSIS
      Returns the sorted, de-duplicated list of repository-relative paths (using '/') that
      belong in the corresponding-source archive.
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory = $true)][string] $ProjectRoot)

    $root = [IO.Path]::GetFullPath($ProjectRoot)
    $result = [System.Collections.Generic.List[string]]::new()
    foreach ($relative in $SourceFiles) { $result.Add($relative) }

    foreach ($relativeDirectory in $SourceDirectories) {
        $directory = Join-Path $root $relativeDirectory
        if (!(Test-Path -LiteralPath $directory -PathType Container)) { continue }
        foreach ($file in Get-ChildItem -LiteralPath $directory -File -Recurse -Force) {
            if ($file.Extension.ToLowerInvariant() -notin $SourceExtensions) { continue }
            $relative = [IO.Path]::GetRelativePath($root, $file.FullName).Replace('\', '/')
            # Never traverse build products or dependency trees that may sit inside a listed directory.
            if ($relative -match '(^|/)(target|node_modules|\.git)(/|$)') { continue }
            $result.Add($relative)
        }
    }
    return @($result | Sort-Object -Unique -CaseSensitive)
}

function Test-SourceExcluded {
    <# Returns the matching $SourceExcluded entry for a repository-relative path, or $null. #>
    [CmdletBinding()]
    param([Parameter(Mandatory = $true)][string] $RelativePath)
    foreach ($entry in $SourceExcluded) {
        if ($entry.Path.EndsWith('/')) {
            if ($RelativePath.StartsWith($entry.Path, [StringComparison]::Ordinal)) { return $entry }
        } elseif ($RelativePath -ceq $entry.Path) {
            return $entry
        }
    }
    return $null
}
